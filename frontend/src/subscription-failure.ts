export function subscriptionFailure(code?: string): string {
  const messages: Record<string, string> = {
    invalid_url:
      "Проверьте адрес подписки: нужен полный URL без имени пользователя и пароля перед адресом сервера.",
    dns_failed:
      "Не удалось получить адрес сервера подписки. Проверьте DNS и доступ контейнера в интернет.",
    destination_refused:
      "Адрес подписки указывает на локальную или служебную сеть. Загрузка с такого адреса запрещена.",
    connect_failed:
      "Контейнер не смог подключиться к серверу подписки. Проверьте доступ к нему из сети роутера.",
    timeout:
      "Загрузка подписки не завершилась вовремя. Контейнер загружает подписку напрямую; рабочие прокси сами по себе не меняют этот путь.",
    tls_failed:
      "Не удалось проверить сертификат сервера подписки. Проверьте адрес и время на роутере; проверку TLS отключать не нужно.",
    redirect_refused:
      "Сервер перенаправляет на недопустимый адрес или с HTTPS на HTTP. Проверьте ссылку подписки.",
    http_error:
      "Сервер подписки вернул ошибку HTTP. Проверьте срок действия и адрес подписки.",
    body_invalid:
      "Ответ сервера не удалось прочитать или он превышает допустимый размер.",
    request_failed:
      "Не удалось загрузить подписку. Проверьте доступ контейнера к серверу подписки.",
  };
  return code && Object.hasOwn(messages, code)
    ? messages[code]
    : "Обновление не удалось. Проверьте доступ к источнику, формат подписки и фильтры.";
}
